export type PixelIconName = keyof typeof ICONS;

export function PixelIcon({ name, className = "" }: { name: PixelIconName; className?: string }) {
  const rows = ICONS[name];
  const rects: React.ReactNode[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === "#") {
        let w = 1;
        while (row[x + w] === "#") w++;
        rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={w} height={1} />);
        x += w;
      } else x++;
    }
  });
  return (
    <svg viewBox="0 0 12 12" className={className} fill="currentColor" shapeRendering="crispEdges" aria-hidden="true">
      {rects}
    </svg>
  );
}

/** The motif: a coloured circle with a black pixel icon in it. */
export function IconDot({
  name,
  color,
  size = 64,
  className = "",
}: {
  name: PixelIconName;
  color: string;
  size?: number;
  className?: string;
}) {
  return (
    <span className={`px-dot ${className}`} style={{ width: size, height: size, background: color }}>
      <PixelIcon name={name} className="px-dot-icon" />
    </span>
  );
}
