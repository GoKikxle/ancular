/**
 * Tiny source origin indicator shown inline with the time.
 *
 *   manual   → nothing (default experience, no noise)
 *   document → faint amber document icon  ("filed from a document")
 *   ai       → faint violet sparkle       ("AI-generated")
 *   null     → nothing (legacy row, column not yet in DB)
 *
 * Kept at very low opacity so it's glanceable without competing with content.
 */
function SourceIcon({ source }: { source?: "manual" | "ai" | "document" | null }) {
  if (!source || source === "manual") return null;

  if (source === "document") {
    return (
      <svg
        width="9"
        height="10"
        viewBox="0 0 9 10"
        fill="none"
        aria-label="Auto-created from document"
        className="mt-px flex-shrink-0 text-amber-400/50"
      >
        <title>Auto-created from document</title>
        <rect x="0.5" y="0.5" width="8" height="9" rx="1.2" stroke="currentColor" strokeWidth="0.85" />
        <path d="M2 3.8h5M2 5.4h5M2 7h3" stroke="currentColor" strokeWidth="0.85" strokeLinecap="round" />
      </svg>
    );
  }

  // ai
  return (
    <svg
      width="9"
      height="9"
      viewBox="0 0 9 9"
      fill="none"
      aria-label="AI-generated"
      className="mt-px flex-shrink-0 text-violet-400/55"
    >
      <title>AI-generated</title>
      {/* Four-pointed sparkle */}
      <path
        d="M4.5 0.5 L5.1 3.9 L8.5 4.5 L5.1 5.1 L4.5 8.5 L3.9 5.1 L0.5 4.5 L3.9 3.9 Z"
        stroke="currentColor"
        strokeWidth="0.7"
        strokeLinejoin="round"
      />
    </svg>
  );
}

// ─── State dot ─────────────────────────────────────────────────────────────────

/**
 * The dot on the vertical connector line changes appearance per state:
 *
 *   current   → sky-400 filled + soft glow ring (signals "right now")
 *   completed → dim hollow dot   (signals "done")
 *   upcoming  → mid hollow dot   (signals "not yet")
 */
function StateDot({ state }: { state: ItemState }) {
  if (state === "current") {
    return (
      <div className="relative z-10 mt-[3px] flex-shrink-0">
        {/* Soft glow halo — static, not animated, keeps the premium feel */}
        <div className="h-[15px] w-[15px] rounded-full border-2 border-sky-400 bg-sky-400 shadow-[0_0_0_4px_rgba(56,189,248,0.15)]" />
      </div>
    );
  }

  if (state === "completed") {
    return (
      <div className="relative z-10 mt-[3px] flex-shrink-0">
        {/* Faintly filled: "used up" */}
        <div className="h-[15px] w-[15px] rounded-full border-2 border-white/[0.10] bg-white/[0.05]" />
      </div>
    );
  }

  // upcoming
  return (
    <div className="relative z-10 mt-[3px] flex-shrink-0">
      <div className="h-[15px] w-[15px] rounded-full border-2 border-white/[0.22] bg-[#0a0a0a]" />
    </div>
  );
}

// ─── Animations ────────────────────────────────────────────────────────────────

const confirmSlide = {
  hidden: { opacity: 0, height: 0 },
  show: {
    opacity: 1,
    height: "auto",
    transition: { duration: 0.18, ease: [0.25, 0.46, 0.45, 0.94] as const },
  },
  exit: {
    opacity: 0,
    height: 0,
    transition: { duration: 0.14, ease: [0.55, 0, 1, 0.45] as const },
  },
};

// ─── Component ─────────────────────────────────────────────────────────────────

export function TimelineCard({ items, tripSlug, hasDocuments }: TimelineCardProps) {
  const [confirmingId, setConfirmingId] = useState<string | null>(null);
  const [deletingId, setDeletingId] = useState<string | null>(null);
  const [editingId, setEditingId] = useState<string | null>(null);
  const [isPending, startTransition] = useTransition();

  // Capture a single stable "now" snapshot for the whole render cycle so every
  // item state computation uses the same reference time.
  const now = useMemo(() => new Date(), []);

  // Pre-compute display state for all items once.
  const states = useMemo(
    () => items.map((item) => computeItemState(item, now)),
    [items, now]
  );

  // Ref attached to the current item — used for the auto-scroll on mount.
  const currentItemRef = useRef<HTMLDivElement>(null);

  // Scroll the current item into view when the timeline first renders.
  // "nearest" avoids scrolling past the page header on short timelines.
  useEffect(() => {
    currentItemRef.current?.scrollIntoView({
      behavior: "smooth",
      block: "nearest",
    });
  }, []); // intentionally runs once on mount only

  function requestConfirm(id: string) {
    setConfirmingId(id);
    setEditingId(null);  // close edit if open for same item
  }

  function cancelConfirm() {
    setConfirmingId(null);
  }

  function handleDelete(id: string) {
    setDeletingId(id);
    setConfirmingId(null);
    startTransition(async () => {
      await deleteTimelineItemAction(id, tripSlug);
      setDeletingId(null);
    });
  }

  function startEditing(id: string) {
    setEditingId(id);
    setConfirmingId(null);  // close delete confirm if open for same item
  }

  function closeEdit() {
    setEditingId(null);
  }

  if (items.length === 0) return null;

  return (
    <section className="rounded-3xl border border-white/[0.08] bg-white/[0.04] p-5">
      <p className="mb-5 text-[11px] uppercase tracking-[0.1em] text-white/35">
        Itinerary
      </p>

      <div className="relative">
        {/* Vertical connector line */}
        <div className="absolute bottom-2 left-[7px] top-2 w-px bg-white/[0.07]" />

        <div>
          {items.map((item, i) => {
            const state = states[i];
            const label = getGroupLabel(i, states);
            const isConfirming = confirmingId === item.id;
            const isDeleting = deletingId === item.id && isPending;

            const isCurrent = state === "current";
            const isCompleted = state === "completed";
            const isEditing = editingId === item.id;

            return (
              <Fragment key={item.id}>

                {/* ── Group label ──────────────────────────────────────────────── */}
                {label && (
                  <div
                    className={`flex items-center gap-3 pl-[31px] ${
                      i > 0 ? "mb-4 mt-6" : "mb-4"
                    }`}
                  >
                    <span className="flex-shrink-0 text-[10px] font-semibold uppercase tracking-[0.12em] text-white/32">
                      {label}
                    </span>
                    <div className="h-px flex-1 bg-white/[0.09]" />
                  </div>
                )}

                {/* ── Item row ─────────────────────────────────────────────────────
                     Row-level opacity encodes state visually without touching
                     individual children. */}
                <div
                  ref={isCurrent ? currentItemRef : undefined}
                  className={`flex items-start gap-4 transition-opacity duration-200 ${
                    isDeleting
                      ? "pointer-events-none opacity-30"
                      : isConfirming || isEditing
                      ? "opacity-55"
                      : isCompleted
                      ? "opacity-40"
                      : "opacity-100"
                  } ${i > 0 && !label ? "mt-6" : i > 0 ? "" : ""}`}
                >

                  {/* State dot */}
                  <StateDot state={state} />

                  {/* Content */}
                  <div className="min-w-0 flex-1 pb-1">

                    {/* Time + source origin */}
                    <div className="flex items-center gap-1.5">
                      <p
                        className={`text-[12px] font-medium tabular-nums ${
                          isCurrent
                            ? "text-sky-400"
                            : isCompleted
                            ? "text-white/28"
                            : "text-sky-400/60"
                        }`}
                      >
                        {item.time}
                      </p>
                      {!isCompleted && <SourceIcon source={item.source} />}
                    </div>

                    {/* Title */}
                    <h3
                      className={`mt-0.5 font-semibold tracking-[-0.01em] ${
                        isCurrent
                          ? "text-[16px] text-white"
                          : isCompleted
                          ? "text-[14px] text-white/45"
                          : "text-[15px] text-white/90"
                      }`}
                    >
                      {item.title}
                    </h3>

                    {/* Note — hidden for completed items */}
                    {!isCompleted && item.note && (
                      <p
                        className={`mt-1 text-[13px] leading-relaxed ${
                          isCurrent ? "text-white/55" : "text-white/38"
                        }`}
                      >
                        {item.note}
                      </p>
                    )}

                    {/* Location chip */}
                    {!isCompleted && item.location && (
                      <p className="mt-1.5 text-[12px] text-white/28">
                        <span className="mr-1 text-white/18">at</span>
                        {item.location}
                      </p>
                    )}

                    {/* Document label chip */}
                    {!isCompleted && item.document_label && (
                      <span className="mt-2 inline-flex items-center gap-1 rounded-full border border-white/[0.08] bg-white/[0.04] px-2 py-0.5 text-[11px] text-white/38">
                        {item.document_label}
                      </span>
                    )}

                    {/* View document CTA — current item only, when documents exist */}
                    {isCurrent && hasDocuments && (
                      <motion.a
                        href="#documents"
                        whileTap={{ scale: 0.97 }}
                        className="mt-3 inline-flex items-center gap-1.5 rounded-full border border-sky-400/25 bg-sky-500/[0.12] px-3 py-1.5 text-[12px] font-medium text-sky-300 transition-colors hover:bg-sky-500/[0.18]"
                      >
                        <DocIcon />
                        View document
                      </motion.a>
                    )}

                  </div>

                  {/* ── Edit + delete triggers ───────────────────────────────────
                       Hidden during delete confirmation and while deleting.
                       When editing is open for this item, hide to avoid clutter. */}
                  {!isConfirming && !isEditing && !isDeleting && (
                    <div className="flex flex-shrink-0 flex-col gap-0.5">
                      <button
                        type="button"
                        onClick={() => startEditing(item.id)}
                        disabled={isPending}
                        aria-label={`Edit "${item.title}"`}
                        className="flex h-8 w-8 items-center justify-center rounded-full text-white/[0.22] transition-colors hover:text-white/45 disabled:opacity-30"
                      >
                        <PencilIcon />
                      </button>
                      <button
                        type="button"
                        onClick={() => requestConfirm(item.id)}
                        disabled={isPending}
                        aria-label={`Delete "${item.title}"`}
                        className="flex h-8 w-8 items-center justify-center rounded-full text-white/[0.22] transition-colors hover:text-white/45 active:text-red-400/70 disabled:opacity-30"
                      >
                        <TrashIcon />
                      </button>
                    </div>
                  )}

                </div>

                {/* ── Inline edit form ─────────────────────────────────────────── */}
                <AnimatePresence initial={false}>
                  {isEditing && (
                    <motion.div
                      key={`edit-${item.id}`}
                      variants={confirmSlide}
                      initial="hidden"
                      animate="show"
                      exit="exit"
                      className="overflow-hidden pl-[31px]"
                    >
                      <EditTimelineItemForm
                        item={item}
                        tripSlug={tripSlug}
                        onCancel={closeEdit}
                        onSaved={closeEdit}
                      />
                    </motion.div>
                  )}
                </AnimatePresence>

                {/* ── Inline delete confirmation ────────────────────────────────── */}
                <AnimatePresence initial={false}>
                  {isConfirming && (
                    <motion.div
                      key={`confirm-${item.id}`}
                      variants={confirmSlide}
                      initial="hidden"
                      animate="show"
                      exit="exit"
                      className="overflow-hidden"
                    >
                      <div className="flex items-center justify-between gap-3 pb-1 pl-[31px] pt-2.5">
                        <p className="text-[12px] text-white/35">
                          Remove this action?
                        </p>
                        <div className="flex flex-shrink-0 gap-2">
                          <button
                            type="button"
                            onClick={cancelConfirm}
                            className="rounded-full border border-white/[0.12] px-3 py-1.5 text-[12px] text-white/40 transition-colors hover:text-white/60"
                          >
                            Cancel
                          </button>
                          <button
                            type="button"
                            onClick={() => handleDelete(item.id)}
                            className="rounded-full border border-red-500/25 bg-red-500/[0.09] px-3 py-1.5 text-[12px] font-medium text-red-400/80 transition-colors hover:bg-red-500/[0.16] hover:text-red-400"
                          >
                            Remove
                          </button>
                        </div>
                      </div>
                    </motion.div>
                  )}
                </AnimatePresence>

              </Fragment>
            );
          })}
        </div>
      </div>
    </section>
  );
}
