"use client";

import { Fragment, useEffect, useMemo, useRef, useState, useTransition } from "react";
import { AnimatePresence, motion } from "framer-motion";
import { computeItemState, getGroupLabel } from "@/lib/timeline-view-model";
import type { ItemState } from "@/lib/timeline-view-model";
import { deleteTimelineItemAction } from "@/app/trips/[tripId]/actions";
import { EditTimelineItemForm } from "./EditTimelineItemForm";

// ─── Types ─────────────────────────────────────────────────────────────────────

export type TimelineItem = {
  id: string;
  /** ISO date string "YYYY-MM-DD". NULL for legacy items without a date. */
  event_date?: string | null;
  time: string;
  title: string;
  note: string;
  /** Physical location or gate info. TODO: backed by `location` column */
  location?: string | null;
  /** Label for an associated document (e.g. "Boarding Pass"). TODO: backed by `document_label` */
  document_label?: string | null;
  /**
   * Origin of the item. NULL for legacy rows created before the source column existed.
   *   manual   → user added via AddActionForm
   *   document → auto-created when a document was attached/uploaded
   *   ai       → generated by the AI itinerary builder
   *
   * TODO: activate once source column is added to DB:
   *   ALTER TABLE timeline_items ADD COLUMN IF NOT EXISTS source TEXT NULL
   *     CHECK (source IS NULL OR source IN ('manual', 'ai', 'document'));
   */
  source?: "manual" | "ai" | "document" | null;
};

type TimelineCardProps = {
  items: TimelineItem[];
  tripSlug: string;
  /** When true, the "View document" CTA is shown on the current item. */
  hasDocuments: boolean;
};

